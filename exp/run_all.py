"""
Run all experiments in sequence and generate RESULTS.md summary.
"""
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from exp.exp_1_run import run_exp_1
from exp.exp_2_run import run_exp_2
from exp.exp_3_run import run_exp_3
from exp.exp_4_run import run_exp_4

RESULTS_DIR = Path(__file__).parent.parent / "results"


def write_results_md(all_outputs: dict) -> None:
    """Write RESULTS.md with experiment findings and metrics."""
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    exp1 = all_outputs.get("exp1", {})
    exp2 = all_outputs.get("exp2", {})
    exp3 = all_outputs.get("exp3", {})
    exp4 = all_outputs.get("exp4", {})

    lines = []
    lines.append("# RESULTS.md — Experiment Summary\n")
    lines.append("> Generated by run_all.py\n")
    lines.append("")

    # ── Experiment 1 ─────────────────────────────────────────────────────────
    lines.append("## Experiment 1: Data Preparation and Market State Classification\n")

    if exp1:
        state1 = exp1.get("state_series1")
        state2 = exp1.get("state_series2")
        centroids1 = exp1.get("centroids1")
        centroids2 = exp1.get("centroids2")

        if state1 is not None:
            lines.append(f"**Asset Set 1:**\n")
            lines.append(f"- Analysis window: {state1.index[0].date()} to {state1.index[-1].date()}")
            lines.append(f"- Total state-labeled trading days: {len(state1)}")
            count1 = state1.value_counts().sort_index()
            total1 = len(state1)
            low_pct1 = sum(count1.get(s, 0) for s in range(1, 4)) / total1 * 100
            lines.append(f"- States 1-3 share: {low_pct1:.1f}% (validation: >50% ✓)")
            if centroids1 is not None:
                lines.append(f"- Centroid range: {centroids1[0]*100:.3f}% (state 1) to {centroids1[-1]*100:.3f}% (state 10)")
            lines.append("")
            lines.append("| State | Count | Share |")
            lines.append("|-------|-------|-------|")
            for s in range(1, 11):
                c = count1.get(s, 0)
                lines.append(f"| {s} | {c} | {c/total1*100:.1f}% |")
            lines.append("")

        if state2 is not None:
            lines.append(f"**Asset Set 2:**\n")
            lines.append(f"- Analysis window: {state2.index[0].date()} to {state2.index[-1].date()}")
            lines.append(f"- Total state-labeled trading days: {len(state2)}")
            count2 = state2.value_counts().sort_index()
            total2 = len(state2)
            low_pct2 = sum(count2.get(s, 0) for s in range(1, 4)) / total2 * 100
            lines.append(f"- States 1-3 share: {low_pct2:.1f}%")
            if centroids2 is not None:
                lines.append(f"- Centroid range: {centroids2[0]*100:.3f}% (state 1) to {centroids2[-1]*100:.3f}% (state 10)")
            lines.append("")

    # ── Experiment 2 ─────────────────────────────────────────────────────────
    lines.append("## Experiment 2: Static Portfolio Weights\n")

    if exp2:
        import numpy as np
        weights1 = exp2.get("weights1", {})
        weights2 = exp2.get("weights2", {})
        strategy_rets1 = exp2.get("strategy_rets1")
        strategy_rets2 = exp2.get("strategy_rets2")

        if weights1:
            lines.append("**Asset Set 1 Weights:**\n")
            lines.append("| Strategy | AAPL | LLY | JPM | AMZN | GOOGL | UPS | PG | XOM | NEE | AMT | LIN |")
            lines.append("|----------|" + "|".join(["------"] * 11) + "|")
            for strat, w in weights1.items():
                row = f"| {strat} | " + " | ".join(f"{wi:.4f}" for wi in w) + " |"
                lines.append(row)
            lines.append("")

        if weights2:
            lines.append("**Asset Set 2 Weights:**\n")
            lines.append("| Strategy | QQQ | SPY | BTC-USD | GLD | TLT |")
            lines.append("|----------|-----|-----|---------|-----|-----|")
            for strat, w in weights2.items():
                row = f"| {strat} | " + " | ".join(f"{wi:.4f}" for wi in w) + " |"
                lines.append(row)
            lines.append("")

    # ── Experiment 3 ─────────────────────────────────────────────────────────
    lines.append("## Experiment 3: Bayesian Markov Transition Matrix\n")

    if exp3:
        diag1 = exp3.get("diagnostics1", {})
        diag2 = exp3.get("diagnostics2", {})

        lines.append("| Metric | Asset Set 1 | Asset Set 2 | Expected Set 1 | Expected Set 2 |")
        lines.append("|--------|-------------|-------------|----------------|----------------|")
        lines.append(f"| SLEM (λ₂) | {diag1.get('slem', 'N/A'):.4f} | {diag2.get('slem', 'N/A'):.4f} | ~0.9584 | ~0.9277 |")
        lines.append(f"| t_rel | {diag1.get('t_rel', 'N/A'):.2f} | {diag2.get('t_rel', 'N/A'):.2f} | ~24.04 | ~13.87 |")
        lines.append(f"| t_mix lower | {diag1.get('t_mix_lower', 'N/A'):.1f} | {diag2.get('t_mix_lower', 'N/A'):.1f} | - | - |")
        lines.append(f"| t_mix upper | {diag1.get('t_mix_upper', 'N/A'):.1f} | {diag2.get('t_mix_upper', 'N/A'):.1f} | - | - |")
        lines.append(f"| max R-hat | {diag1.get('max_rhat', 'N/A'):.4f} | {diag2.get('max_rhat', 'N/A'):.4f} | ≤1.1 | ≤1.1 |")
        lines.append("")

    # ── Experiment 4 ─────────────────────────────────────────────────────────
    lines.append("## Experiment 4: Dynamic Portfolio Performance\n")

    if exp4:
        res1 = exp4.get("results1", {})
        res2 = exp4.get("results2", {})

        for label, res in [("Asset Set 1", res1), ("Asset Set 2", res2)]:
            if res:
                fm = res.get("full_metrics")
                if fm is not None:
                    lines.append(f"**{label} Full-Period Metrics:**\n")
                    lines.append("| Strategy | Compound Return | Daily Vol | Sharpe Ratio |")
                    lines.append("|----------|----------------|-----------|--------------|")
                    for strat in fm.index:
                        row = fm.loc[strat]
                        lines.append(
                            f"| {strat} | {row['compound_return']:.4f} "
                            f"| {row['volatility']:.4f} "
                            f"| {row['sharpe']:.2f} |"
                        )
                    lines.append("")

                best = res.get("best_strategy")
                if best is not None:
                    lines.append(f"**{label} Best Strategy Per State:**\n")
                    lines.append("| State | Best Strategy |")
                    lines.append("|-------|---------------|")
                    for s in range(1, 11):
                        lines.append(f"| {s} | {best.get(s, 'N/A')} |")
                    lines.append("")

    lines.append("## Figures Generated\n")
    lines.append("- `fig1_asset_set1_vol_states.png` — Asset Set 1 rolling vol by state")
    lines.append("- `fig2_asset_set2_vol_states.png` — Asset Set 2 rolling vol by state")
    lines.append("- `fig3_asset_set1_transition_matrix.png` — Asset Set 1 transition heatmap")
    lines.append("- `fig3b_asset_set2_transition_matrix.png` — Asset Set 2 transition heatmap")
    lines.append("- `fig4_asset_set1_portfolio_value.png` — Asset Set 1 portfolio growth")
    lines.append("- `fig5_asset_set1_annual_sharpe.png` — Asset Set 1 annual Sharpe")
    lines.append("- `fig6_asset_set2_portfolio_value.png` — Asset Set 2 portfolio growth")
    lines.append("- `fig7_asset_set2_annual_sharpe.png` — Asset Set 2 annual Sharpe")
    lines.append("")

    md_content = "\n".join(lines)
    with open(RESULTS_DIR / "RESULTS.md", "w") as f:
        f.write(md_content)
    print(f"\nSaved: {RESULTS_DIR / 'RESULTS.md'}")


def main():
    """Execute all experiments in sequence."""
    start_time = time.time()

    print("╔══════════════════════════════════════════════════════╗")
    print("║  QUANTITATIVE FINANCE EXPERIMENT SUITE               ║")
    print("║  Market State Classification & Dynamic Portfolio      ║")
    print("╚══════════════════════════════════════════════════════╝\n")

    # Run experiment 1
    t0 = time.time()
    exp1_outputs = run_exp_1()
    print(f"\n[Exp 1 completed in {time.time()-t0:.1f}s]\n")

    # Run experiment 2
    t0 = time.time()
    exp2_outputs = run_exp_2(exp1_outputs)
    print(f"\n[Exp 2 completed in {time.time()-t0:.1f}s]\n")

    # Run experiment 3
    t0 = time.time()
    exp3_outputs = run_exp_3(exp1_outputs)
    print(f"\n[Exp 3 completed in {time.time()-t0:.1f}s]\n")

    # Run experiment 4
    t0 = time.time()
    exp4_outputs = run_exp_4(exp1_outputs, exp2_outputs, exp3_outputs)
    print(f"\n[Exp 4 completed in {time.time()-t0:.1f}s]\n")

    # Write RESULTS.md
    write_results_md({
        "exp1": exp1_outputs,
        "exp2": exp2_outputs,
        "exp3": exp3_outputs,
        "exp4": exp4_outputs,
    })

    total_time = time.time() - start_time
    print(f"\n{'='*60}")
    print(f"All experiments completed in {total_time:.1f}s")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()
